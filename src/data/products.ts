function stockFor(sizes: Size[], colors: ColorOption[], qtyBySize: number[]): StockEntry[] {
  const entries: StockEntry[] = []
  colors.forEach((color, colorIdx) => {
    sizes.forEach((size, sizeIdx) => {
      const base = qtyBySize[sizeIdx] ?? 0
      const qty = colorIdx === 0 ? base : Math.max(0, base - colorIdx)
      entries.push({ size, color: color.name, quantity: qty })
    })
  })
  return entries
}

